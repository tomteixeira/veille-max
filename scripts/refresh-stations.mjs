#!/usr/bin/env node
// Writes a migration that fills `public.stations` with the full name of every
// station code found in the SNCF `tgvmax` dataset (spec, "Station reference").
// Usage: `npm run stations:refresh`, then review and commit the new migration.
//
// Sources:
// - the codes: the `tgvmax` dataset (SNCF Voyageurs open data, ODbL), whose
//   5-character codes are only named at city level for a few big cities;
// - the names: trainline-eu/stations (ODbL), whose `sncf_id` column holds the
//   same codes;
// - CITY_LEVEL_NAMES below, written by hand for the codes the dataset names
//   « PARIS (intramuros) », « LYON (intramuros) » or « LILLE (intramuros) ».
// A code missing from trainline keeps the dataset's own name, in title case.
//
// The migration upserts every row, so it can run again safely. It never
// deletes a station: a code that left the dataset may still be in a route.

import { writeFileSync } from 'node:fs'

const TGVMAX_RECORDS = 'https://ressources.data.sncf.com/api/explore/v2.1/catalog/datasets/tgvmax/records'
const TRAINLINE_STATIONS = 'https://raw.githubusercontent.com/trainline-eu/stations/master/stations.csv'

const CITY_LEVEL_NAMES = {
  FRPLY: 'Paris Gare de Lyon',
  FRPBE: 'Paris Bercy',
  FRPMO: 'Paris Montparnasse',
  FRPNO: 'Paris Gare du Nord',
  FRPST: 'Paris Gare de l’Est',
  FRPAZ: 'Paris Austerlitz',
  FRLPD: 'Lyon Part-Dieu',
  FRLPE: 'Lyon Perrache',
  FRLLE: 'Lille Europe',
  FRADJ: 'Lille Flandres',
}

async function fetchOk(url) {
  const response = await fetch(url)
  if (!response.ok) throw new Error(`${url} answered ${response.status}`)
  return response
}

/** Every station code of the dataset, with the dataset's own name. */
async function readDatasetStations() {
  const stations = new Map()
  for (const side of ['origine', 'destination']) {
    const query = new URLSearchParams({ select: `${side}_iata,${side}`, group_by: `${side}_iata,${side}`, limit: '10000' })
    const { total_count: total, results } = await (await fetchOk(`${TGVMAX_RECORDS}?${query}`)).json()
    if (results.length !== total) throw new Error(`tgvmax returned ${results.length} of ${total} ${side} stations`)
    for (const row of results) stations.set(row[`${side}_iata`], row[side])
  }
  return stations
}

/** trainline-eu/stations names, by SNCF code. */
async function readTrainlineNames() {
  const [header, ...lines] = (await (await fetchOk(TRAINLINE_STATIONS)).text()).split('\n')
  const columns = header.split(';')
  const codeColumn = columns.indexOf('sncf_id')
  const nameColumn = columns.indexOf('name')
  if (codeColumn < 0 || nameColumn < 0) throw new Error('trainline stations.csv has no sncf_id or name column')

  const names = new Map()
  for (const line of lines) {
    const fields = line.split(';')
    const code = fields[codeColumn]
    if (code && !names.has(code)) names.set(code, fields[nameColumn])
  }
  return names
}

const SMALL_WORDS = new Set(['au', 'aux', 'de', 'des', 'du', 'en', 'et', 'la', 'le', 'les', 'sur'])

/** « COMMERCY ZONE DU SEUGNON » → « Commercy Zone du Seugnon ». */
function titleCase(datasetName) {
  return datasetName
    .toLowerCase()
    .split(/\s+/)
    .map((word, index) => (index > 0 && SMALL_WORDS.has(word) ? word : word.charAt(0).toUpperCase() + word.slice(1)))
    .join(' ')
}

function sqlString(text) {
  return `'${text.replaceAll('\'', '\'\'')}'`
}

const [datasetStations, trainlineNames] = await Promise.all([readDatasetStations(), readTrainlineNames()])

const fallbacks = []
const rows = [...datasetStations]
  .map(([code, datasetName]) => {
    const name = CITY_LEVEL_NAMES[code] ?? trainlineNames.get(code)
    if (name) return { code, name }
    fallbacks.push(code)
    return { code, name: titleCase(datasetName) }
  })
  .sort((a, b) => a.code.localeCompare(b.code))

const now = new Date()
const version = now.toISOString().replace(/\D/g, '').slice(0, 14)
const path = `supabase/migrations/${version}_refresh_stations.sql`

writeFileSync(path, `-- Station reference: the full name of every station code in the SNCF \`tgvmax\`
-- dataset on ${now.toISOString().slice(0, 10)}. Generated by \`npm run stations:refresh\`
-- (scripts/refresh-stations.mjs). Do not edit by hand: change the script and run it again.
--
-- Names: trainline-eu/stations (ODbL) through its \`sncf_id\` column, hand-written for the
-- ${Object.keys(CITY_LEVEL_NAMES).length} codes the dataset only names at city level.
-- ${fallbacks.length === 0 ? 'Every code was found in trainline-eu/stations.' : `Not in trainline-eu/stations, named from the dataset: ${fallbacks.join(', ')}.`}

insert into public.stations (code, name) values
${rows.map(({ code, name }) => `  (${sqlString(code)}, ${sqlString(name)})`).join(',\n')}
on conflict (code) do update set name = excluded.name
where stations.name is distinct from excluded.name;
`)

console.log(`Wrote ${path}: ${rows.length} stations, ${fallbacks.length} named from the dataset (${fallbacks.join(', ')}).`)
