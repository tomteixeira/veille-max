#!/usr/bin/env node
// Writes `.env` with the connection settings of the running local Supabase
// stack, under the names the app reads (see `.env.example`).
// Usage: `npm run supabase:start && npm run supabase:env`.

import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'

const status = JSON.parse(
  execFileSync('npx', ['supabase', 'status', '--output', 'json'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] }),
)

const env = {
  NUXT_PUBLIC_SUPABASE_URL: status.API_URL,
  NUXT_PUBLIC_SUPABASE_KEY: status.PUBLISHABLE_KEY,
  NUXT_SUPABASE_SECRET_KEY: status.SECRET_KEY,
}

const missing = Object.entries(env).filter(([, value]) => !value).map(([name]) => name)
if (missing.length > 0) {
  console.error(`Local Supabase did not report: ${missing.join(', ')}. Is the stack running (npm run supabase:start)?`)
  process.exit(1)
}

const lines = [
  '# Generated by `npm run supabase:env` from the local Supabase stack. Do not commit.',
  ...Object.entries(env).map(([name, value]) => `${name}=${value}`),
]
writeFileSync('.env', `${lines.join('\n')}\n`)
console.log(`Wrote .env (${Object.keys(env).join(', ')})`)
